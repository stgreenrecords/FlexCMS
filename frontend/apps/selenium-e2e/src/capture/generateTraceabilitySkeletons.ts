function writeTraceabilityCsv(
  templates: TemplateFixture[],
  components: ComponentFixture[],
  generatedAt: string,
): void {
  const headers = [
    'entity_kind',
    'case_id',
    'title',
    'slug',
    'spec_path',
    'manifest_path',
    'normalized_html',
    'screenshot_evidence',
    'blocker_count',
    'coverage_broken_images',
    'coverage_font_loading',
    'coverage_console_errors',
    'coverage_primary_cta',
    'coverage_responsive_breakpoints',
    'coverage_basic_accessibility',
    'status',
    'notes',
  ];

  const rows: string[][] = [];

  for (const fixture of templates) {
    rows.push([
      'template',
      fixture.caseId,
      fixture.title,
      fixture.slug,
      `frontend/apps/selenium-e2e/src/cases/templates/${fixture.slug}.spec.ts`,
      fixture.manifestPath,
      fixture.normalizedHtml,
      fixture.screenshotEvidence,
      String(fixture.blockerCount),
      'planned',
      'planned',
      'planned',
      'planned',
      'planned',
      'planned',
      fixture.captureStatus === 'captured' ? 'skeleton' : 'skeleton-no-capture',
      fixture.captureStatus === 'captured'
        ? 'Generated by REB-06; implementation deferred to REB-12.'
        : 'Generated by REB-06; source folder exists but capture evidence was skipped in REB-02.',
    ]);
  }

  for (const fixture of components) {
    rows.push([
      'component-group',
      fixture.caseId,
      fixture.title,
      fixture.slug,
      `frontend/apps/selenium-e2e/src/cases/components/${fixture.slug}.spec.ts`,
      fixture.manifestPath,
      fixture.normalizedHtml,
      fixture.screenshotEvidence,
      String(fixture.blockerCount),
      'planned',
      'planned',
      'planned',
      'planned',
      'planned',
      'planned',
      fixture.captureStatus === 'captured' ? 'skeleton' : 'skeleton-no-capture',
      fixture.captureStatus === 'captured'
        ? 'Generated by REB-06; implementation deferred to REB-12.'
        : 'Generated by REB-06; source folder exists but capture evidence was skipped in REB-02.',
    ]);
  }

  const fileBody = [
    `# generated_at=${generatedAt}`,
    headers.join(','),
    ...rows.map((row) => row.map(csvEscape).join(',')),
    '',
  ].join('\n');

  fs.writeFileSync(path.join(generatedRoot, 'qa-traceability-matrix.csv'), fileBody, 'utf8');
}

function buildTemplateTitleMap(contracts: TemplateContract[]): Map<string, string> {
  const map = new Map<string, string>();
  for (const contract of contracts) {
    const folder = contract.templateSource?.folder;
    if (folder) {
      map.set(path.basename(folder), contract.title);
    }
    map.set(toSnakeCase(contract.name), contract.title);
  }
  return map;
}

function buildComponentTitleMap(contracts: ComponentContract[]): Map<string, string> {
  const map = new Map<string, string>();
  const grouped = new Map<string, Set<string>>();

  for (const contract of contracts) {
    const groupSlug = `component_library_${toSnakeCase(contract.groupName)}`;
    if (!grouped.has(groupSlug)) {
      grouped.set(groupSlug, new Set<string>());
    }
    grouped.get(groupSlug)!.add(contract.groupName);
  }

  for (const [slug, names] of grouped.entries()) {
    map.set(slug, Array.from(names).sort()[0]);
  }

  return map;
}

function mergePagesWithSkipped(manifest: GlobalManifest, kind: PageKind): GlobalManifestPage[] {
  const bySlug = new Map<string, GlobalManifestPage>();

  for (const page of manifest.pages) {
    if (page.kind === kind) {
      bySlug.set(page.slug, page);
    }
  }

  for (const skipped of manifest.skippedFolders ?? []) {
    if (skipped.kind !== kind || bySlug.has(skipped.slug)) {
      continue;
    }
    bySlug.set(skipped.slug, {
      kind,
      slug: skipped.slug,
      manifestPath: '',
      normalizedHtml: '',
      screenshotEvidence: '',
      blockerCount: 0,
    });
  }

  return Array.from(bySlug.values()).sort(sortBySlug);
}

function sortBySlug(left: GlobalManifestPage, right: GlobalManifestPage): number {
  return left.slug.localeCompare(right.slug);
}

function csvEscape(value: string): string {
  if (value.includes(',') || value.includes('"') || value.includes('\n')) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

function titleFromSlug(slug: string): string {
  return slug
    .split('_')
    .map(capitalize)
    .join(' ');
}

function titleFromComponentSlug(slug: string): string {
  return titleFromSlug(slug.replace(/^component_library_/, ''));
}

function toSnakeCase(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

function capitalize(value: string): string {
  return value ? `${value[0].toUpperCase()}${value.slice(1)}` : value;
}

function pad(value: number): string {
  return String(value).padStart(2, '0');
}

function ensureDir(dirPath: string): void {
  fs.mkdirSync(dirPath, { recursive: true });
}

function readJson<T>(filePath: string): T {
  const raw = fs.readFileSync(filePath, 'utf8');
  return JSON.parse(raw) as T;
}

function escapeSingleQuotes(value: string): string {
  return value.replace(/'/g, "\\'");
}

main();

