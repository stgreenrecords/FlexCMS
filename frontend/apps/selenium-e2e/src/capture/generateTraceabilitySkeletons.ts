import * as fs from 'node:fs';
import * as path from 'node:path';

type PageKind = 'templates' | 'components';

interface GlobalManifestPage {
  kind: PageKind;
  slug: string;
  manifestPath: string;
  normalizedHtml: string;
  screenshotEvidence: string;
  blockerCount: number;
}

interface GlobalManifest {
  generatedAt: string;
  pages: GlobalManifestPage[];
  skippedFolders: Array<{ kind: PageKind; slug: string; reason: string }>;
}

interface TemplateContract {
  name: string;
  title: string;
  templateSource?: {
    folder?: string;
  };
}

interface ComponentContract {
  groupName: string;
  resourceType: string;
}

interface TemplateFixture {
  caseId: string;
  slug: string;
  title: string;
  captureStatus: 'captured' | 'skipped';
  manifestPath: string;
  normalizedHtml: string;
  screenshotEvidence: string;
  blockerCount: number;
}

interface ComponentFixture {
  caseId: string;
  slug: string;
  title: string;
  captureStatus: 'captured' | 'skipped';
  manifestPath: string;
  normalizedHtml: string;
  screenshotEvidence: string;
  blockerCount: number;
}

const packageRoot = path.resolve(__dirname, '../..');
const repoRoot = path.resolve(packageRoot, '../../..');
const designRoot = path.join(repoRoot, 'Design', 'tut-usa');
const generatedRoot = path.join(designRoot, 'generated');
const manifestPath = path.join(designRoot, 'manifest.json');
const templateContractsPath = path.join(generatedRoot, 'template-contracts.json');
const componentContractsPath = path.join(generatedRoot, 'component-contracts.json');

const fixturesRoot = path.join(packageRoot, 'src', 'fixtures');
const templateCasesRoot = path.join(packageRoot, 'src', 'cases', 'templates');
const componentCasesRoot = path.join(packageRoot, 'src', 'cases', 'components');

function main(): void {
  const manifest = readJson<GlobalManifest>(manifestPath);
  const templateContracts = readJson<TemplateContract[]>(templateContractsPath);
  const componentContracts = readJson<ComponentContract[]>(componentContractsPath);

  const templateTitleBySlug = buildTemplateTitleMap(templateContracts);
  const componentTitleBySlug = buildComponentTitleMap(componentContracts);

  const templatePages = mergePagesWithSkipped(manifest, 'templates');
  const componentPages = mergePagesWithSkipped(manifest, 'components');

  const templateFixtures: TemplateFixture[] = templatePages.map((page, index) => ({
    caseId: `TPL-${pad(index + 1)}`,
    slug: page.slug,
    title: templateTitleBySlug.get(page.slug) ?? titleFromSlug(page.slug),
    captureStatus: page.kind === 'templates' && page.manifestPath ? 'captured' : 'skipped',
    manifestPath: page.manifestPath,
    normalizedHtml: page.normalizedHtml,
    screenshotEvidence: page.screenshotEvidence,
    blockerCount: page.blockerCount,
  }));

  const componentFixtures: ComponentFixture[] = componentPages.map((page, index) => ({
    caseId: `CMP-${pad(index + 1)}`,
    slug: page.slug,
    title: componentTitleBySlug.get(page.slug) ?? titleFromComponentSlug(page.slug),
    captureStatus: page.kind === 'components' && page.manifestPath ? 'captured' : 'skipped',
    manifestPath: page.manifestPath,
    normalizedHtml: page.normalizedHtml,
    screenshotEvidence: page.screenshotEvidence,
    blockerCount: page.blockerCount,
  }));

  ensureDir(fixturesRoot);
  ensureDir(templateCasesRoot);
  ensureDir(componentCasesRoot);
  ensureDir(generatedRoot);

  writeTemplateFixtureFile(templateFixtures);
  writeComponentFixtureFile(componentFixtures);
  writeFixturesIndex();

  writeTemplateSpecSkeletons(templateFixtures);
  writeComponentSpecSkeletons(componentFixtures);

  writeTraceabilityCsv(templateFixtures, componentFixtures, manifest.generatedAt);

  console.log(
    `[REB-06] Generated ${templateFixtures.length} template fixtures/spec skeletons and ${componentFixtures.length} component fixtures/spec skeletons.`,
  );
}

function writeTemplateFixtureFile(fixtures: TemplateFixture[]): void {
  const body = [
    '/**',
    ' * Generated by `src/capture/generateTraceabilitySkeletons.ts` for REB-06.',
    ' * Do not hand-edit; regenerate with `pnpm generate:traceability`.',
    ' */',
    'export interface TemplateManifestEntry {',
    '  caseId: string;',
    '  slug: string;',
    '  title: string;',
    "  captureStatus: 'captured' | 'skipped';",
    '  manifestPath: string;',
    '  normalizedHtml: string;',
    '  screenshotEvidence: string;',
    '  blockerCount: number;',
    '}',
    '',
    `export const templateManifest: TemplateManifestEntry[] = ${JSON.stringify(fixtures, null, 2)};`,
    '',
  ].join('\n');

  fs.writeFileSync(path.join(fixturesRoot, 'template-manifest.ts'), body, 'utf8');
}

