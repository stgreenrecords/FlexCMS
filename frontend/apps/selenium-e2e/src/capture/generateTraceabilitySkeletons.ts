function writeFixturesIndex(): void {
  const body = [
    "export { templateManifest } from './template-manifest';",
    "export { componentManifest } from './component-manifest';",
    '',
  ].join('\n');

  fs.writeFileSync(path.join(fixturesRoot, 'index.ts'), body, 'utf8');
}

function writeTemplateSpecSkeletons(fixtures: TemplateFixture[]): void {
  for (const fixture of fixtures) {
    const filePath = path.join(templateCasesRoot, `${fixture.slug}.spec.ts`);
    fs.writeFileSync(filePath, buildTemplateSpec(fixture), 'utf8');
  }
}

function writeComponentSpecSkeletons(fixtures: ComponentFixture[]): void {
  for (const fixture of fixtures) {
    const filePath = path.join(componentCasesRoot, `${fixture.slug}.spec.ts`);
    fs.writeFileSync(filePath, buildComponentSpec(fixture), 'utf8');
  }
}

